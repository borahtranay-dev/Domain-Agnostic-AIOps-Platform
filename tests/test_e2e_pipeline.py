def test_e2e_incident_detection_to_healing_pipeline(api_client):
    """Verify complete end-to-end multi-service failure lifecycle."""
    
    # -------------------------------------------------------------
    # STEP 1: External Client App encounters a failure
    # -------------------------------------------------------------
    raw_event_payload = {
        "service_id": "auth-service",
        "environment_id": "production",
        "type": "telemetry",
        "source": "kubernetes/node-exporter",
        "summary": "QueuePool limit of size 10 overflow 20 reached, connection timed out",
        "payload": {
            "error": "OperationalError: connection pool exhausted at max 30",
            "active_connections": 30,
            "max_allowed": 30,
            "latency_ms": 12450.0,
        },
    }

    # -------------------------------------------------------------
    # STEP 2: Ingestion Gateway validates & stores event
    # -------------------------------------------------------------
    event_res = api_client.post("/api/v1/events", json=raw_event_payload)
    assert event_res.status_code == 201
    ingested_event = event_res.json()
    assert ingested_event["service_id"] == "auth-service"
    assert ingested_event["type"] == "telemetry"
    event_id = ingested_event["id"]

    # -------------------------------------------------------------
    # STEP 3: Incident is correlated and opened in SRE Cockpit
    # -------------------------------------------------------------
    incident_payload = {
        "title": "Critical Outage: Database Connection Pool Exhausted",
        "severity": "critical",
        "status": "open",
        "service_id": "auth-service",
        "environment_id": "production",
        "event_ids": [event_id],
    }
    inc_res = api_client.post("/api/v1/incidents", json=incident_payload)
    assert inc_res.status_code == 201
    incident_data = inc_res.json()
    incident_id = incident_data["id"]
    assert incident_data["status"] == "open"

    # -------------------------------------------------------------
    # STEP 4: Telemetry Evidence artifacts are harvested
    # -------------------------------------------------------------
    ev1 = Evidence(
        incident_id=incident_id,
        kind=EvidenceKind.LOG,
        source="postgresql-primary",
        content="FATAL: remaining connection slots are reserved for non-replication superuser connections. Active: 30/30",
    )
    ev2 = Evidence(
        incident_id=incident_id,
        kind=EvidenceKind.METRIC,
        source="prometheus/pool_saturation",
        content="database_pool_utilization{service='auth-service'} 1.00 (100% saturated for >180s)",
    )
    incident_obj = Incident(**incident_data)

    # -------------------------------------------------------------
    # STEP 5: AI-Worker executes RAG Grounded Diagnosis
    # -------------------------------------------------------------
    # 5a. Switch namespace to apps/ai-worker cleanly
    ai_worker_dir = Path(__file__).resolve().parents[1] / "apps" / "ai-worker"
    
    # Remove api_path from sys.path and purge src module cache
    if str(api_path) in sys.path:
        sys.path.remove(str(api_path))
    for mod in list(sys.modules.keys()):
        if mod == "src" or mod.startswith("src."):
            del sys.modules[mod]
            
    if str(ai_worker_dir) not in sys.path:
        sys.path.insert(0, str(ai_worker_dir))
    else:
        sys.path.remove(str(ai_worker_dir))
        sys.path.insert(0, str(ai_worker_dir))

    from src.runbook_store import runbook_store
    from src.diagnosis_service import diagnosis_engine

    # 5a. Vector Runbook Retrieval
    matched_runbooks = runbook_store.retrieve("QueuePool limit of size 10 overflow 20 reached connection pool exhausted", top_k=1)
    assert len(matched_runbooks) >= 1
    rb_item = matched_runbooks[0]["runbook"]
    assert rb_item.id == "RB-001"
    assert "Connection Pool" in rb_item.title

    # 5b. LangChain RAG Inference
    rag_result = diagnosis_engine.diagnose_incident(incident_obj, [ev1, ev2])
    diag = rag_result["diagnosis"]
    plan = rag_result["remediation_plan"]

    # Assertions on AI output
    assert isinstance(diag, Diagnosis)
    assert diag.incident_id == incident_id
    assert 0.0 <= diag.confidence <= 1.0
    assert diag.confidence >= 0.65  # Calibrated confidence bound
    assert len(diag.supporting_evidence_ids) >= 1
    assert "connection pool" in diag.probable_root_cause.lower()

    # -------------------------------------------------------------
    # STEP 6: AI-Worker generates Remediation Plan Contract
    # -------------------------------------------------------------
    assert isinstance(plan, RemediationPlan)
    assert plan.incident_id == incident_id
    assert len(plan.actions) >= 1
    action = plan.actions[0]
    assert action.action_type in [ActionType.CONFIG_UPDATE, ActionType.CONTAINER_RESTART]
    assert plan.status == PlanStatus.DRAFTED

    # -------------------------------------------------------------
    # STEP 7: Incident updates to AWAITING_APPROVAL in Cockpit
    # -------------------------------------------------------------
    update_res = api_client.patch(
        f"/api/v1/incidents/{incident_id}/status?status=awaiting_approval"
    )
    assert update_res.status_code == 200
    assert update_res.json()["status"] == "awaiting_approval"

    # -------------------------------------------------------------
    # STEP 8: Human SRE Authorizes Remediation (APPROVED -> RESOLVED)
    # -------------------------------------------------------------
    # Human approval gate
    resolve_res = api_client.patch(
        f"/api/v1/incidents/{incident_id}/status?status=resolved"
    )
    assert resolve_res.status_code == 200
    assert resolve_res.json()["status"] == "resolved"
    assert resolve_res.json()["resolved_at"] is not None

    # -------------------------------------------------------------
    # STEP 9: Domain-Agnosticity Test (Zero E-Commerce Term Leak)
    # -------------------------------------------------------------
    banned_terms = ["order_id", "cart", "payment_status", "checkout", "inventory"]
    full_pipeline_text = (
        str(ingested_event) + str(incident_data) + diag.probable_root_cause + plan.rationale
    ).lower()

    for banned in banned_terms:
        assert banned not in full_pipeline_text, f"Domain leak detected in E2E pipeline: {banned}"


def test_e2e_rejection_of_unauthorized_fields(api_client):
    """Verify that external malicious payloads with illegal attributes are rejected."""
    illegal_payload = {
        "service_id": "auth-service",
        "environment_id": "production",
        "type": "telemetry",
        "source": "external-hacker",
        "summary": "Attempting payload injection",
        "order_id": "ORD-ILLEGAL-999",  # Banned field
    }
    res = api_client.post("/api/v1/events", json=illegal_payload)
    assert res.status_code == 422  # Strict Pydantic extra='forbid' validation
